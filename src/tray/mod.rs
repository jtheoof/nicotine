//! System tray icon, shown while "close to tray" is on.
//!
//! Linux uses a StatusNotifierItem over D-Bus (`sni`), the protocol KDE
//! Plasma, waybar's tray module and GNOME's AppIndicator extension
//! display. Windows uses the notification area (`win`).
//!
//! The menu offers Open, Toggle previews, Restack (where supported) and
//! Quit; a left click opens the panel. Actions that change panel state go
//! to the panel through `panel_bridge` so they persist like panel edits.

use crate::config::LiveSettings;
use crate::panel_bridge::{self, UiRequest};
use std::sync::{Arc, Mutex};

#[cfg(unix)]
mod sni;
#[cfg(windows)]
mod win;

#[cfg(unix)]
use sni as platform;
#[cfg(windows)]
use win as platform;

/// The logo as square raw RGBA rasters, generated by build.rs.
const ICON_32: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/tray-32.rgba"));
// Windows' tray takes a single icon and scales it; only Linux sends both.
#[cfg_attr(windows, allow(dead_code))]
const ICON_64: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/tray-64.rgba"));

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    Open,
    TogglePreviews,
    Restack,
    Quit,
}

fn dispatch(action: Action) {
    match action {
        Action::Open => {
            panel_bridge::request(UiRequest::Open);
        }
        Action::TogglePreviews => {
            panel_bridge::request(UiRequest::TogglePreviews);
        }
        Action::Restack => {
            let _ = crate::daemon::send_command("stack");
        }
        Action::Quit => {
            panel_bridge::request(UiRequest::Quit);
        }
    }
}

/// A live tray icon; dropping it removes the icon.
pub struct Tray {
    _handle: platform::Handle,
}

impl std::fmt::Debug for Tray {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Tray")
    }
}

/// Push the current preview visibility to the tray menu's "Hide previews" /
/// "Show previews" entry. Call after anything flips `LiveSettings.show_previews`; the
/// menu otherwise only re-reads it when the user clicks an item, which is
/// before the panel has applied a tray toggle. No-op without a tray.
pub fn refresh() {
    platform::refresh();
}

/// Show the tray icon. Fails when the desktop has nowhere to show it (on
/// Linux: no StatusNotifierItem host is running), with a reason for the
/// panel to display.
pub fn spawn(live: Arc<Mutex<LiveSettings>>, restack_supported: bool) -> Result<Tray, String> {
    platform::spawn(live, restack_supported).map(|handle| Tray { _handle: handle })
}
